/**
 * Godot 4 .tres SpriteFrames resource format
 */
export function exportGodot4SpriteFrames(project: SpriteAtlasProject): string {
  const imageName = `${project.title.toLowerCase().replace(/\s+/g, '_')}.png`;
  let out = `[gd_resource type="SpriteFrames" load_steps=2 format=3]\n\n`;
  out += `[ext_resource type="Texture2D" path="res://${imageName}" id="1_atlas"]\n\n`;

  // AtlasTexture sub-resources
  const frameKeys = Object.keys(project.frames);
  frameKeys.forEach((key, idx) => {
    const f = project.frames[key];
    out += `[sub_resource type="AtlasTexture" id="AtlasTexture_${f.id}"]\n`;
    out += `atlas = ExtResource("1_atlas")\n`;
    out += `region = Rect2(${f.sourceRect.x}, ${f.sourceRect.y}, ${f.sourceRect.width}, ${f.sourceRect.height})\n\n`;
  });

  out += `[resource]\n`;
  out += `animations = [{\n`;

  const anims = project.clips.map((clip) => {
    const frameRefs = clip.frameIds
      .map((id) => `{\n"duration": 1.0,\n"texture": SubResource("AtlasTexture_${id}")\n}`)
      .join(', ');

    return `{\n"frames": [${frameRefs}],\n"loop": ${clip.loop},\n"name": &"${clip.name.toLowerCase()}",\n"speed": ${clip.fps}.0\n}`;
  });

  out += anims.join(',\n');
  out += `\n}]\n`;

  return out;
}

/**
 * CSS Keyframe Animations
 */
export function exportCSSKeyframes(project: SpriteAtlasProject): string {
  let css = `/* Generated by Sprite Sheet Viewer & Animation Studio */\n`;
  css += `/* Image: ${project.imageDimensions.width}x${project.imageDimensions.height}px */\n\n`;

  project.clips.forEach((clip) => {
    const clipFrames = clip.frameIds
      .map((id) => project.frames[id])
      .filter(Boolean);

    if (clipFrames.length === 0) return;

    const baseFrame = clipFrames[0];
    const durationSec = (clipFrames.length / clip.fps).toFixed(2);
    const className = `sprite-${clip.name.toLowerCase().replace(/\s+/g, '-')}`;

    css += `.${className} {\n`;
    css += `  width: ${baseFrame.sourceRect.width}px;\n`;
    css += `  height: ${baseFrame.sourceRect.height}px;\n`;
    css += `  background-image: url('${project.imageUrl.startsWith('data:') ? 'spritesheet.png' : project.imageUrl}');\n`;
    css += `  image-rendering: pixelated;\n`;
    css += `  image-rendering: crisp-edges;\n`;
    css += `  animation: anim-${clip.name.toLowerCase()} ${durationSec}s steps(1) ${clip.loop ? 'infinite' : 'forwards'};\n`;
    css += `}\n\n`;

    css += `@keyframes anim-${clip.name.toLowerCase()} {\n`;
    clipFrames.forEach((f, idx) => {
      const pct = ((idx / clipFrames.length) * 100).toFixed(1);
      css += `  ${pct}% { background-position: -${f.sourceRect.x}px -${f.sourceRect.y}px; }\n`;
    });
    css += `  100% { background-position: -${baseFrame.sourceRect.x}px -${baseFrame.sourceRect.y}px; }\n`;
    css += `}\n\n`;
  });

  return css;
}

/**
 * Unity Coordinate CSV & Hitbox Manifest
 */
export function exportUnityCSV(project: SpriteAtlasProject): string {
  let csv = 'Name,X,Y,Width,Height,PivotX,PivotY,HitboxCount,HitboxTypes\n';
  Object.values(project.frames).forEach((f) => {
    const pivotX = +(f.anchorPoint.x / f.sourceRect.width).toFixed(3);
    const pivotY = +(f.anchorPoint.y / f.sourceRect.height).toFixed(3);
    const hbCount = f.hitboxes.length;
    const hbTypes = f.hitboxes.map((h) => `${h.type}[${h.x},${h.y},${h.width},${h.height}]`).join('|');

    csv += `"${f.id}",${f.sourceRect.x},${f.sourceRect.y},${f.sourceRect.width},${f.sourceRect.height},${pivotX},${pivotY},${hbCount},"${hbTypes}"\n`;
  });
  return csv;
}
