import { SpriteAtlasProject } from '../types/sprite';

/**
 * TexturePacker JSON (Array format) - Phaser 3 / PixiJS compatible
 */
export function exportTexturePackerArray(project: SpriteAtlasProject): string {
  const frames = Object.values(project.frames).map((f) => ({
    filename: `${f.id}.png`,
    frame: {
      x: f.sourceRect.x,
      y: f.sourceRect.y,
      w: f.sourceRect.width,
      h: f.sourceRect.height,
    },
    rotated: false,
    trimmed: false,
    spriteSourceSize: {
      x: 0,
      y: 0,
      w: f.sourceRect.width,
      h: f.sourceRect.height,
    },
    sourceSize: {
      w: f.sourceRect.width,
      h: f.sourceRect.height,
    },
    pivot: {
      x: +(f.anchorPoint.x / f.sourceRect.width).toFixed(3),
      y: +(f.anchorPoint.y / f.sourceRect.height).toFixed(3),
    },
    hitboxes: f.hitboxes,
  }));

  const data = {
    frames,
    meta: {
      app: 'Sprite Sheet Viewer & Animation Studio',
      version: '1.0',
      image: `${project.title.toLowerCase().replace(/\s+/g, '_')}.png`,
      format: 'RGBA8888',
      size: {
        w: project.imageDimensions.width,
        h: project.imageDimensions.height,
      },
      scale: '1',
      animations: project.clips.reduce((acc, clip) => {
        acc[clip.name] = clip.frameIds.map((id) => `${id}.png`);
        return acc;
      }, {} as Record<string, string[]>),
    },
  };

  return JSON.stringify(data, null, 2);
}

